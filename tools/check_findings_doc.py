"""Check that docs/FINDINGS.md is what the check catalog generates today.

  python tools/check_findings_doc.py [--exe x64/Release/PhantomReconCli.exe] [--fix]

The file is generated by `PhantomReconCli.exe --findings-md`. When someone edits a
check's text in CheckCatalog.cpp and forgets to regenerate, the tracked copy drifts;
this check fails the build with the first differing lines. --fix writes the
generated text over the tracked file. Line endings are ignored (Git may check the
file out with CRLF).
"""
from __future__ import annotations

import argparse
import difflib
import pathlib
import sys
import tempfile

from release_common import DEFAULT_EXE_DIR, ROOT, configure_console, log, run_program

TRACKED = ROOT / "docs" / "FINDINGS.md"


def normalised(path: pathlib.Path) -> list:
    text = path.read_bytes().decode("utf-8-sig")
    return text.replace("\r\n", "\n").split("\n")


def main() -> int:
    configure_console()
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--exe", type=pathlib.Path, default=DEFAULT_EXE_DIR / "PhantomReconCli.exe")
    parser.add_argument("--fix", action="store_true")
    args = parser.parse_args()

    with tempfile.TemporaryDirectory(prefix="phantomrecon_findings_") as temp:
        generated = pathlib.Path(temp) / "FINDINGS.md"
        result = run_program([args.exe, "--findings-md", generated], timeout=120)
        if result.returncode != 0 or not generated.is_file():
            print(f"FINDINGS CHECK FAILED: --findings-md exited {result.returncode}: {result.stdout}{result.stderr}",
                  flush=True)
            return 1
        fresh = normalised(generated)
        tracked = normalised(TRACKED) if TRACKED.is_file() else []
        if fresh == tracked:
            print(f"docs/FINDINGS.md matches the catalog ({len(fresh)} lines).", flush=True)
            return 0
        if args.fix:
            TRACKED.write_bytes(generated.read_bytes())
            log("docs/FINDINGS.md rewritten from the catalog")
            return 0
    diff = list(difflib.unified_diff(tracked, fresh, "docs/FINDINGS.md (tracked)", "generated", lineterm="", n=1))
    print("FINDINGS CHECK FAILED: docs/FINDINGS.md differs from the catalog. Run "
          "python tools/check_findings_doc.py --fix and commit the result.", flush=True)
    for line in diff[:60]:
        print(line, flush=True)
    if len(diff) > 60:
        print(f"... {len(diff) - 60} more diff line(s)", flush=True)
    return 1


if __name__ == "__main__":
    sys.exit(main())
